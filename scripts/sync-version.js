// svelte-package has no build-time `define`, so the version Clerk sees in `sdkMetadata`
// and the backend user agent is written to a source file instead.
import { readFileSync, writeFileSync } from 'node:fs';

const { version } = JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8'));
writeFileSync(
	new URL('../src/lib/version.ts', import.meta.url),
	`// Generated by scripts/sync-version.js. Do not edit.\nexport const VERSION = '${version}';\n`
);
